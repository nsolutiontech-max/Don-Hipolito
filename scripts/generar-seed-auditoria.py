"""Generate the immutable 84-item audit template from the source workbook."""
import re
from pathlib import Path
from xml.etree import ElementTree as ET
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
BLOCKS = {
    "COCINA": [(8, 19, "Procesos"), (20, 23, "Manipulación"), (24, 31, "Mise en place"),
               (32, 38, "Heladeras/Freezer"), (39, 47, "Limpieza")],
    "SALON_GENERAL": [(51, 64, "Salón"), (65, 69, "Vereda"), (70, 75, "Depósito Cajas"),
                      (76, 81, "Depósito Bebidas"), (82, 85, "Depósito Env. Vacíos"),
                      (86, 89, "Baños"), (90, 94, "General")],
}


def sql(value):
    return "'" + value.replace("'", "''") + "'"


def read_sheet():
    with ZipFile(ROOT / "Docs/Planillas Digitalizables.xlsx") as book:
        strings = ["".join(si.itertext()) for si in ET.fromstring(book.read("xl/sharedStrings.xml"))]
        root = ET.fromstring(book.read("xl/worksheets/sheet7.xml"))
        cells = {}
        for cell in root.findall(".//m:sheetData/m:row/m:c", NS):
            value = cell.find("m:v", NS)
            if value is None:
                continue
            cells[cell.attrib["r"]] = strings[int(value.text)] if cell.get("t") == "s" else value.text
        return cells


def items():
    source = read_sheet()
    result = []
    order = 0
    for block, groups in BLOCKS.items():
        block_order = 0
        for start, end, group in groups:
            for row in range(start, end + 1):
                text = " ".join(source.get(f"C{row}", "").split())
                if not text:
                    raise ValueError(f"Missing audit criterion at C{row}")
                order += 1
                block_order += 1
                result.append({
                    "codigo": f"AUD_{'C' if block == 'COCINA' else 'S'}{block_order:02d}",
                    "bloque": block,
                    "grupo": group,
                    "texto": text,
                    "orden": order,
                    "orden_bloque": block_order,
                    "celda": f"Auditoría!C{row}",
                })
    return result


def generate():
    rows = items()
    assert len(rows) == 84
    assert sum(r["bloque"] == "COCINA" for r in rows) == 40
    assert sum(r["bloque"] == "SALON_GENERAL" for r in rows) == 44
    values = ",\n".join(
        "(" + ",".join(sql(r[key]) for key in ["codigo", "bloque", "grupo", "texto"])
        + f",{r['orden']},{r['orden_bloque']})"
        for r in rows
    )
    content = (
        "-- Generated by scripts/generar-seed-auditoria.py from Auditoría!C8:C94.\n"
        "insert into public.auditoria_plantillas(codigo,nombre,version,activa)\n"
        "values ('AUDITORIA_2026','Auditoría de operaciones',1,true)\n"
        "on conflict (codigo) do update set nombre=excluded.nombre, version=excluded.version, activa=excluded.activa;\n"
        "create temporary table import_audit_items(codigo text,bloque text,grupo text,texto text,orden int,orden_bloque int) on commit drop;\n"
        "insert into import_audit_items values\n"
        + values
        + ";\n"
        "insert into public.auditoria_items(plantilla_id,codigo,bloque,grupo,texto,orden,orden_bloque)\n"
        "select p.id,i.codigo,i.bloque,i.grupo,i.texto,i.orden,i.orden_bloque\n"
        "from import_audit_items i\n"
        "join public.auditoria_plantillas p on p.codigo='AUDITORIA_2026'\n"
        "on conflict (codigo) do update set bloque=excluded.bloque, grupo=excluded.grupo,\n"
        "  texto=excluded.texto, orden=excluded.orden, orden_bloque=excluded.orden_bloque;\n"
        "drop table pg_temp.import_audit_items;\n"
        "do $$ begin\n"
        "  if (select count(*) from public.auditoria_items) <> 84 then\n"
        "    raise exception 'Audit template must contain exactly 84 criteria';\n"
        "  end if;\n"
        "end $$;\n"
    )
    (ROOT / "supabase/seed5_auditoria.sql").write_text(content, encoding="utf-8")
    print("Generated 84 audit criteria: 40 Cocina + 44 Salón/General.")


if __name__ == "__main__":
    generate()
