"""Generate a deterministic inventory seed, retaining existing product identities."""
import json
import re
import unicodedata
from collections import Counter
from pathlib import Path
from xml.etree import ElementTree as ET
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}


def normalize(value):
    ascii_value = unicodedata.normalize("NFKD", value).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", " ", ascii_value.lower()).strip()


def sql(value):
    return "'" + str(value).replace("'", "''") + "'"


def read_sheets():
    with ZipFile(ROOT / "Docs/Planillas Digitalizables.xlsx") as book:
        strings = ["".join(si.itertext()) for si in ET.fromstring(book.read("xl/sharedStrings.xml"))]
        sheets = []
        for index in range(1, 11):
            root = ET.fromstring(book.read(f"xl/worksheets/sheet{index}.xml"))
            cells = {}
            for cell in root.findall(".//m:sheetData/m:row/m:c", NS):
                value = cell.find("m:v", NS)
                if value is not None:
                    cells[cell.attrib["r"]] = strings[int(value.text)] if cell.get("t") == "s" else value.text
                elif cell.get("t") == "inlineStr":
                    cells[cell.attrib["r"]] = "".join(cell.find("m:is", NS).itertext())
            sheets.append(cells)
        return sheets


def inventory_items(sheets):
    result = []
    for index, code, end in [(0, "STOCK_A", 64), (1, "STOCK_B", 67), (2, "STOCK_C", 65), (7, "BEBIDAS", 53)]:
        section = "Papelería" if code == "STOCK_C" else ""
        section_order = 0
        last_section = None
        for row in range(7 if code == "BEBIDAS" else 8, end + 1):
            section = sheets[index].get(f"A{row}", section).strip()
            name = sheets[index].get(f"B{row}", "").strip()
            if not name:
                continue
            display_section = section
            presentation = ""
            if code == "BEBIDAS":
                presentation = {"350cc": "350 cc", "500cc": "500 cc", "Litro": "1 L", "Lata": "Lata", "Porrón": "Porrón"}.get(section, "")
                if section == "Litro":
                    display_section = "Gaseosas · 1 L" if row < 36 else "Cervezas · 1 L"
            if display_section != last_section:
                section_order += 1
                last_section = display_section
            result.append({"codigo": code, "seccion": display_section, "seccion_orden": section_order,
                           "categoria": "Bebidas" if code == "BEBIDAS" else section,
                           "nombre": name, "presentacion": presentation,
                           "orden": sum(item["codigo"] == code for item in result) + 1,
                           "celda": f"sheet{index + 1}!B{row}"})
    return result


def generate():
    items = inventory_items(read_sheets())
    assert Counter(item["codigo"] for item in items) == {"STOCK_A": 57, "STOCK_B": 60, "STOCK_C": 58, "BEBIDAS": 47}
    assert len({(i["codigo"], i["categoria"], i["nombre"], i["presentacion"]) for i in items}) == 222
    legacy_text = "\n".join((ROOT / f"supabase/{name}").read_text(encoding="utf-8") for name in ["seed.sql", "seed2.sql"])
    legacy = {(normalize(cat), normalize(name)): (cat, name)
              for cat, name in re.findall(r"\('([^']*)','([^']*)','(?:KG|UN|LT|PAQ|ATADO|CAJA)'", legacy_text)}
    aliases = {
        ("Aceites", "Aceite Freidora"): ("Aceites", "Aceite de Freidora"),
        ("Frutos Secos", "Almendras"): ("Frutos Secos", "Almendra"),
        ("Verdulería", "Morrones"): ("Verdulería", "Morrón"),
        ("Verdulería", "Zuchini"): ("Verdulería", "Zucchini"),
        ("Harinas", "Sémola de trigo"): ("Harinas", "Sémola"),
        ("Verdulería", "Huevos"): ("Aceites", "Huevos"),
        ("Masa", "Tapas de Empanada"): ("Especias", "Tapas de Empanada"),
        ("Aceites", "Manteca"): ("Varios", "Manteca"),
    }
    values = []
    for item in items:
        old = aliases.get((item["categoria"], item["nombre"]))
        if not old and not item["presentacion"]:
            old = legacy.get((normalize(item["categoria"]), normalize(item["nombre"])))
        old = old or ("", "")
        fields = [item[k] for k in ["codigo", "seccion", "categoria", "nombre", "presentacion"]] + list(old)
        values.append("(" + ",".join(map(sql, fields)) + f",{item['orden']},{item['seccion_orden']})")
    seed = """-- Generated by scripts/generar-seed3.py; run after migration 003.
insert into public.categorias(nombre, orden) values ('Papelería',11),('Limpieza',12),('Bebidas',13)
on conflict (nombre) do nothing;
insert into public.planillas_inventario(codigo,nombre,modo,orden) values
('STOCK_A','Stock Mercadería A','STOCK_PEDIDO',1),
('STOCK_B','Stock Mercadería B','STOCK_PEDIDO',2),
('STOCK_C','Papelería y Limpieza','STOCK_PEDIDO',3),
('BEBIDAS','Reposición de Bebidas','STOCK_UBICACIONES',4)
on conflict (codigo) do nothing;
create temporary table import_items(codigo text,seccion text,categoria text,nombre text,presentacion text,
  anterior_categoria text,anterior_nombre text,orden int,seccion_orden int) on commit drop;
insert into import_items values
""" + ",\n".join(values) + ";\n" + """
-- Reuse matching IDs; never delete or merge unmatched products.
do $$ declare r record; begin
  for r in select distinct categoria,nombre,presentacion,anterior_categoria,anterior_nombre from import_items loop
    if not exists (select 1 from public.productos p join public.categorias c on c.id=p.categoria_id
      where c.nombre=r.categoria and p.nombre=r.nombre and p.presentacion=r.presentacion) then
      update public.productos set nombre=r.nombre, categoria_id=(select id from public.categorias where nombre=r.categoria)
        where nombre=r.anterior_nombre and presentacion='' and categoria_id=(select id from public.categorias where nombre=r.anterior_categoria);
      if not found then
        insert into public.productos(categoria_id,nombre,presentacion,unidad_medida,stock_minimo,stock_ideal)
          values ((select id from public.categorias where nombre=r.categoria),r.nombre,r.presentacion,'POR_DEFINIR',0,null);
      end if;
    end if;
  end loop;
end $$;
insert into public.planilla_secciones(planilla_id,nombre,orden)
select distinct p.id,i.seccion,i.seccion_orden from import_items i
join public.planillas_inventario p on p.codigo=i.codigo
on conflict (planilla_id,nombre) do update set orden=excluded.orden;
insert into public.planilla_items(planilla_id,seccion_id,producto_id,orden)
select pl.id,s.id,p.id,i.orden from import_items i
join public.planillas_inventario pl on pl.codigo=i.codigo
join public.planilla_secciones s on s.planilla_id=pl.id and s.nombre=i.seccion
join public.categorias c on c.nombre=i.categoria
join public.productos p on p.categoria_id=c.id and p.nombre=i.nombre and p.presentacion=i.presentacion
on conflict (planilla_id,producto_id) do update set seccion_id=excluded.seccion_id,orden=excluded.orden;
do $$ begin
  if (select count(*) from public.planilla_items) <> 222 then raise exception 'Catalogue reconciliation incomplete'; end if;
end $$;
drop table pg_temp.import_items;
"""
    (ROOT / "supabase/seed3_planillas.sql").write_text(seed, encoding="utf-8")
    (ROOT / "Docs/catalogo-conciliado.json").write_text(json.dumps(items, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("Generated 222 inventory rows with source-cell references.")
    generate_tasks(read_sheets())


def generate_tasks(sheets):
    rows = []
    for index, area, last in [(4, "COCINA", 53), (5, "SALON", 40)]:
        for row in range(5, last + 1):
            name = " ".join(sheets[index][f"A{row}"].split())
            hour = ""
            if area == "SALON" and row <= 14:
                minutes = round(float(sheets[index][f"B{row}"]) * 24 * 60)
                hour = f"{minutes // 60:02d}:{minutes % 60:02d}"
            rows.append((area, name, f"{area}_R{row}", hour, row - 4))
    assert len(rows) == 85
    values = ",\n".join("(" + ",".join(map(sql, r[:4])) + f",{r[4]})" for r in rows)
    content = """-- Generated source occurrences: 49 kitchen rows and 36 dining-room rows.
create temporary table import_tasks(area text,nombre text,codigo text,hora text,orden int) on commit drop;
insert into import_tasks values
""" + values + ";\n" + """
insert into public.actividades(area,nombre,grupo,orden)
select area,nombre,case when area='COCINA' then 'Cocina' else 'Salón' end,min(orden) from import_tasks group by area,nombre
on conflict (area,nombre) do nothing;
insert into public.actividad_programaciones(actividad_id,codigo,hora_objetivo,orden)
select a.id,i.codigo,nullif(i.hora,''),i.orden from import_tasks i
join public.actividades a on a.area=i.area and a.nombre=i.nombre
on conflict (codigo) do nothing;
drop table pg_temp.import_tasks;
insert into public.salon_frecuencias(orden,fase,nombre,frecuencia) values
"""
    master = []
    for row in range(5, 25):
        name = " ".join(sheets[8][f"B{row}"].split())
        freq = sheets[8][f"M{row}"]
        master.append(f"({row-4},{sql('APERTURA' if row<=17 else 'CIERRE')},{sql(name)},{sql(freq)})")
    content += ",\n".join(master) + "\non conflict (orden) do nothing;\n"
    (ROOT / "supabase/seed4_tareas.sql").write_text(content, encoding="utf-8")
    print("Generated 85 task occurrences and 20 opening/closing frequency definitions.")


if __name__ == "__main__":
    generate()
