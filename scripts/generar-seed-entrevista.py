"""Generate the interview evaluation template from the source workbook."""
from pathlib import Path
from xml.etree import ElementTree as ET
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
SECTIONS = [
    ("SEC01", 7, "A", range(8, 14), 14, 15, None),
    ("SEC02", 17, "A", range(19, 24), 24, 25, 18),
    ("SEC03", 27, "A", range(29, 35), 35, 36, 28),
    ("SEC04", 38, "A", range(39, 47), 47, 48, None),
    ("SEC05", 7, "G", range(9, 14), 14, 15, 8),
    ("SEC06", 17, "G", range(18, 28), 28, 29, None),
]


def sql(value):
    return "'" + str(value).replace("'", "''") + "'"


def read_sheet():
    with ZipFile(ROOT / "Docs/Planillas Digitalizables.xlsx") as book:
        strings = ["".join(si.itertext()) for si in ET.fromstring(book.read("xl/sharedStrings.xml"))]
        root = ET.fromstring(book.read("xl/worksheets/sheet10.xml"))
        cells = {}
        for cell in root.findall(".//m:sheetData/m:row/m:c", NS):
            value = cell.find("m:v", NS)
            if value is None:
                continue
            cells[cell.attrib["r"]] = strings[int(value.text)] if cell.get("t") == "s" else value.text
        return cells


def template_items():
    cells = read_sheet()
    criteria = []
    global_order = 0
    for order, (code, title_row, column, criteria_rows, observation_row, result_row, instruction_row) in enumerate(SECTIONS, 1):
        title = cells[f"{column}{title_row}"]
        instruction = cells.get(f"{column}{instruction_row}", "") if instruction_row else ""
        for row in criteria_rows:
            text = cells.get(f"{column}{row}", "")
            if not text:
                raise ValueError(f"Missing interview criterion at {column}{row}")
            global_order += 1
            criteria.append((code, title, instruction, order, global_order, text))
    return criteria


def generate():
    items = template_items()
    assert len(items) == 40
    section_rows = []
    seen = set()
    for code, title, instruction, order, _, _ in items:
        if code not in seen:
            seen.add(code)
            section_rows.append((code, title, instruction, order))
    values = ",\n".join(
        "(" + ",".join(sql(value) for value in (code, title, instruction, criterion_order, text)) + ")"
        for code, title, instruction, order, criterion_order, text in items
    )
    section_values = ",\n".join(
        "(" + ",".join(sql(value) for value in row) + ")" for row in section_rows
    )
    content = (
        "-- Generated by scripts/generar-seed-entrevista.py from Check List Entrevista Práctica.\n"
        "insert into public.entrevista_plantillas(codigo,nombre,version,activa)\n"
        "values ('ENTREVISTA_PRACTICA','Evaluación práctica de cocina',1,true)\n"
        "on conflict (codigo) do update set nombre=excluded.nombre, version=excluded.version, activa=excluded.activa;\n"
        "create temporary table import_sections(codigo text,titulo text,instruccion text,orden int) on commit drop;\n"
        "insert into import_sections values\n" + section_values + ";\n"
        "insert into public.entrevista_secciones(plantilla_id,codigo,titulo,instruccion,orden)\n"
        "select p.id,i.codigo,i.titulo,i.instruccion,i.orden from import_sections i\n"
        "join public.entrevista_plantillas p on p.codigo='ENTREVISTA_PRACTICA'\n"
        "on conflict (plantilla_id,codigo) do update set titulo=excluded.titulo,\n"
        "  instruccion=excluded.instruccion, orden=excluded.orden;\n"
        "create temporary table import_criteria(seccion text,titulo text,instruccion text,orden int,texto text) on commit drop;\n"
        "insert into import_criteria values\n" + values + ";\n"
        "insert into public.entrevista_criterios(plantilla_id,seccion_id,codigo,texto,orden)\n"
        "select p.id,s.id,'ENC_' || right('00' || c.orden::text,3),c.texto,c.orden\n"
        "from import_criteria c\n"
        "join public.entrevista_plantillas p on p.codigo='ENTREVISTA_PRACTICA'\n"
        "join public.entrevista_secciones s on s.plantilla_id=p.id and s.titulo=c.titulo\n"
        "on conflict (codigo) do update set seccion_id=excluded.seccion_id, texto=excluded.texto, orden=excluded.orden;\n"
        "drop table pg_temp.import_sections;\n"
        "drop table pg_temp.import_criteria;\n"
        "do $$ begin\n"
        "  if (select count(*) from public.entrevista_secciones) <> 6 or\n"
        "     (select count(*) from public.entrevista_criterios) <> 40 then\n"
        "    raise exception 'Interview template must contain 6 sections and 40 criteria';\n"
        "  end if;\n"
        "end $$;\n"
    )
    (ROOT / "supabase/seed6_entrevistas.sql").write_text(content, encoding="utf-8")
    print("Generated 6 interview sections and 40 criteria.")


if __name__ == "__main__":
    generate()
